"""
Wait loops made into tick loops, for games built with "virtual frames"
(framework/tools/imagebuild.py; M.U.L.E., Archon).

In such a game the raster IRQ ran the frame logic, and the main program waits
for it in loops like
    $5481  LDA $70 / BNE $5481        (until the transport ship has landed)
In the online build the frame logic only runs in ticks (the game's tick routine,
e.g. mule_tick), so each such loop must tick while it waits. A game lists its
loops and generates the patches:

    import waitpatch
    waitpatch.generate(root, "orig/game.bin", tick="mule_tick", segments=[("WAITS", 230)],
                       sites={...}, heads={...}, calls={...}, jumps={...})
    -> src/waits.inc (include it in src/main.s) and src/areas-waits.json (include it in the
       areas file: {"include": "areas-waits.json"})

sites   {address: what}: two instructions, a load or compare (LDA/LDX/LDY/BIT/CMP/CPX/CPY,
        zero page or absolute) and a branch back; it becomes JSR to a stub (plus NOPs to the same
        length):   stub: load / branch -> tick / RTS       tick: JSR <tick> / JMP stub
        so the registers and flags at the end are the original's. When the branch goes
        back further than the load (a loop with more checks), the tick drops the stub's
        return address and jumps to the branch's target instead. {address: (what,
        "first")}: also the target of a longer loop: the stub ticks once before it checks.
heads   {address: (bytes, what)}: the first instructions of a loop (3 bytes or more,
        no branches, no stack) become JSR to a stub: JSR <tick> / <the instructions> / RTS
calls   {address: what}: a JSR at the head of a loop: JSR stub = JSR <tick> / JMP <target>
jumps   {address: what}: a JMP back that closes a loop: JMP stub = JSR <tick> / JMP <target>
segments [(name, room)]: the stubs fill these segments in this order (a game may have no
        room for all of them in one piece); every one is declared, even when empty.
"""
from __future__ import annotations

import json
import os

import dis6502


def decode(mem: bytes, pc: int) -> tuple[str, int, str, int]:
    """(load instruction text, its length, branch mnemonic, branch target) at pc; checks the pattern."""
    mn, mode = dis6502.OPS[mem[pc]]
    n = dis6502.MODES[mode]
    assert mn in ("LDA", "LDX", "LDY", "BIT", "CMP", "CPX", "CPY") and mode in ("zp", "abs"), f"${pc:04X}: {mn} {mode}"
    load = dis6502.fmt(mn, mode, mem[pc + 1:pc + n], pc)
    bmn, bmode = dis6502.OPS[mem[pc + n]]
    off = mem[pc + n + 1]
    target = (pc + n + 2 + (off - 256 if off > 127 else off)) & 0xFFFF
    assert bmode == "rel" and pc - 100 <= target <= pc, f"${pc:04X}: not a branch back"
    return load, n, bmn, target


def generate(root: str, snapshot: str, tick: str, segments: list[tuple[str, int]], sites: dict,
             heads: dict | None = None, calls: dict | None = None, jumps: dict | None = None,
             tool: str = "tools/waits.py") -> int:
    """Writes <root>/src/waits.inc and src/areas-waits.json; returns the number of loops."""
    heads, calls, jumps = heads or {}, calls or {}, jumps or {}
    with open(os.path.join(root, snapshot), "rb") as f:
        mem = f.read()
    inc = [f"; generated by {tool}: the main program's wait loops as tick loops", ""]
    inc += [f'        .segment "{name}"' for name, _ in segments]   # all exist, even empty (ld65
    inc += [""]                                                    # places what follows by them)
    areas = []
    used = {name: 0 for name, _ in segments}

    def seg(size: int) -> str:
        """the segment for a stub of size bytes: the first with room"""
        for name, room in segments:
            if used[name] + size <= room:
                used[name] += size
                return f'        .segment "{name}"'
        raise SystemExit(f"{tool}: no room for the wait loop stubs (segments)")

    for pc, what in sorted(sites.items()):
        first = isinstance(what, tuple)
        if first:
            what = what[0]
        load, n, branch, target = decode(mem, pc)
        inc += [f'        .segment "P_{pc:04X}"',
                f"        jsr     wait_{pc:04x}           ; was {load} / {branch} *-{n}: {what}"]
        if n + 2 > 3:
            inc.append(f"        .res    {n + 2 - 3}, $EA")
        inc += [seg(n + 2 + 1 + 3 + (3 if target == pc else 5) + (3 if first else 0))]
        if first:
            inc += [f"wait_{pc:04x}:", f"        jsr     {tick}       ; (first: a longer loop comes back here)"]
            inc += [f"wait_{pc:04x}_check:"]
        else:
            inc += [f"wait_{pc:04x}:"]
        inc += [
                f"        {load.split()[0].lower()}     {load.split()[1]}",
                f"        {branch.lower()}     :+",
                "        rts",
                f":       jsr     {tick}"]
        if target == pc:
            inc += [f"        jmp     wait_{pc:04x}{'_check' if first else ''}", ""]
        else:
            inc += ["        pla                     ; (not back here: to the loop's start)",
                    "        pla", f"        jmp     ${target:04X}", ""]
        areas.append({"start": f"{pc:04X}", "end": f"{pc + n + 1:04X}", "what": f"wait loop -> ticks: {what}"})
    for pc, (nbytes, what) in sorted(heads.items()):
        code, q = [], pc
        while q < pc + nbytes:
            mn, mode = dis6502.OPS[mem[q]]
            n = dis6502.MODES[mode]
            assert mn not in ("JMP", "JSR", "RTS", "RTI", "PHA", "PLA", "PHP", "PLP") and mode != "rel", \
                f"${q:04X}: {mn} cannot move into a stub"
            code.append((mem[q:q + n], dis6502.fmt(mn, mode, mem[q + 1:q + n], q)))
            q += n
        assert q == pc + nbytes, f"${pc:04X}: {nbytes} bytes is not a whole number of instructions"
        inc += [f'        .segment "P_{pc:04X}"',
                f"        jsr     head_{pc:04x}           ; loop head: {what}"]
        if nbytes > 3:
            inc.append(f"        .res    {nbytes - 3}, $EA")
        inc += [seg(3 + nbytes + 1), f"head_{pc:04x}:", f"        jsr     {tick}"]
        inc += [f"        .byte   {', '.join(f'${b:02X}' for b in raw)}   ; {text}" for raw, text in code]
        inc += ["        rts", ""]
        areas.append({"start": f"{pc:04X}", "end": f"{pc + nbytes - 1:04X}", "what": f"wait loop head -> a tick: {what}"})
    for pc, what in sorted(calls.items()):
        assert mem[pc] == 0x20, f"${pc:04X}: not a JSR"
        target = mem[pc + 1] | mem[pc + 2] << 8
        inc += [f'        .segment "P_{pc:04X}"',
                f"        jsr     call_{pc:04x}           ; was JSR ${target:04X}, in a loop on {what}",
                seg(6), f"call_{pc:04x}:", f"        jsr     {tick}",
                f"        jmp     ${target:04X}", ""]
        areas.append({"start": f"{pc:04X}", "end": f"{pc + 2:04X}", "what": f"wait loop call -> a tick first: {what}"})
    for pc, what in sorted(jumps.items()):
        assert mem[pc] == 0x4C, f"${pc:04X}: not a JMP"
        target = mem[pc + 1] | mem[pc + 2] << 8
        inc += [f'        .segment "P_{pc:04X}"',
                f"        jmp     jump_{pc:04x}           ; was JMP ${target:04X}, closing a loop on {what}",
                seg(6), f"jump_{pc:04x}:", f"        jsr     {tick}",
                f"        jmp     ${target:04X}", ""]
        areas.append({"start": f"{pc:04X}", "end": f"{pc + 2:04X}", "what": f"wait loop jump -> a tick first: {what}"})
    with open(os.path.join(root, "src", "waits.inc"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(inc))
    with open(os.path.join(root, "src", "areas-waits.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(areas, f, indent=1)
    return len(sites) + len(heads) + len(calls) + len(jumps)
