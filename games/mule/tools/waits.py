#!/usr/bin/env python3
"""
The main program's tight wait loops, made into tick loops (online / DETTEST builds).

In the original the raster IRQ runs the frame logic, and the main program waits
for it in loops like
    $5481  LDA $70 / BNE $5481        (until the transport ship has landed)
In the online build the frame logic only runs in ticks (src/main.s, mule_tick),
so each such loop must tick while it waits. Every site below is two
instructions, a load (LDA/LDX/LDY/BIT, zero page or absolute) and a branch back
to it; it becomes JSR to a stub (plus NOPs to the same length):
    stub:  load / branch -> tick / RTS        tick: JSR mule_tick / JMP stub
so the registers and flags at the end are the original's. When the branch goes
back further than the load (a loop with more checks), the tick drops the stub's
return address and jumps to the branch's target instead. A site marked "first"
is also the target of a longer loop: its stub ticks once before it checks.

Longer wait loops (HEADS) tick at their head: the first instructions of the loop
(3 bytes or more, no branches) become JSR to a stub that ticks and then runs
them:   stub:  JSR mule_tick / <the instructions> / RTS

Loops whose head is a JSR (CALLS) tick in that call: JSR stub, stub = JSR
mule_tick / JMP <the original target>.

Loops closed by a JMP back (JUMPS) tick there: JMP stub, stub = JSR mule_tick /
JMP <the original target>.

    python tools/waits.py      writes src/waits.inc and src/areas-waits.json
(tools/build.py runs it before every build.) The sites were found with a flow
trace of the game (every two-instruction loop of the main program on memory
the frame logic writes) and by running the online build until it hung.
"""
from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "..", "..", "framework", "tools"))
import dis6502  # noqa: E402

SNAPSHOT = os.path.join(ROOT, "orig", "mule-972b.bin")

# address: what it waits for
SITES = {
    0x407B: "the button latch $35",
    0x4BD7: "the frame task's flag $70",
    0x50C4: "the button latch $35",
    0x50D9: "the button latch $35",
    0x5481: "the transport ship: $70",
    0x582C: "an event's animation: $74 (or $42)",
    0x64F5: "$74",
    0x7925: "the frame task's flag $45",
    0x795E: "the auction's clock $5C (trading)",
    0x7E82: "the frame task's flag $45",
    0x7F56: "$40",
    0x8F7E: "$E1AD",
    0x9D05: "the count-down $5A",
    0xA7B9: "the count-down $5C",
    0xABFA: "$40",
    0xAE1F: ("a sprite's position ($D002), moved by the frame task; the loop to $AE2D", "first"),
    0xB5FC: "the frame task's flag $45",
    0xB74A: "$40",
    0xB9FF: "the frame task's flag $45",
    0xBAD8: "$40",
}

# loop head: (bytes replaced, what the loop waits for)
HEADS = {
    0x4CCB: (4, "the count-down $5A or all buttons ($2C)"),
    0x597A: (5, "an event's sprite: $D010 (moved by the frame task)"),
    0x5981: (5, "an event's sprite: $D002 >= $58 (idem)"),
    0x6AE9: (3, "the player's button $49,Y"),
    0x90EE: (4, "$E1B5-$E1B8 all $FF (the frame task)"),
    0xA75B: (3, "a button $49,Y or the count-down $5A"),
    0xB303: (4, "the count-down $5A or all buttons ($2C)"),
}

# JSR at the head of a wait loop: what the loop waits for
CALLS = {
    0x4F99: "the clock $14 (or a key, $6911)",
    0x6B2F: "the clock $14 (or a key, $6911)",
}

# JMP back that closes a wait loop: what the loop waits for
JUMPS = {
    0x5068: "the status summary: all buttons ($4D, $2C) or the count-down $5A",
    0xA8F5: "the town: the player walking (the frame task), the time $6A",
    0xA917: "the town: idem",
    0xAA5A: "the town: idem",
    0xADA2: "the map: the player walking, the time $6A",
}


def decode(mem: bytes, pc: int) -> tuple[str, int, str, int]:
    """(load instruction text, its length, branch mnemonic, branch target) at pc; checks the pattern."""
    mn, mode = dis6502.OPS[mem[pc]]
    n = dis6502.MODES[mode]
    assert mn in ("LDA", "LDX", "LDY", "BIT") and mode in ("zp", "abs"), f"${pc:04X}: {mn} {mode}"
    load = dis6502.fmt(mn, mode, mem[pc + 1:pc + n], pc)
    bmn, bmode = dis6502.OPS[mem[pc + n]]
    off = mem[pc + n + 1]
    target = (pc + n + 2 + (off - 256 if off > 127 else off)) & 0xFFFF
    assert bmode == "rel" and pc - 100 <= target <= pc, f"${pc:04X}: not a branch back"
    return load, n, bmn, target


def generate() -> None:
    with open(SNAPSHOT, "rb") as f:
        mem = f.read()
    inc = ["; generated by tools/waits.py: the main program's tight wait loops as tick loops", ""]
    areas = []
    for pc, what in sorted(SITES.items()):
        first = isinstance(what, tuple)
        if first:
            what = what[0]
        load, n, branch, target = decode(mem, pc)
        inc += [f'        .segment "P_{pc:04X}"',
                f"        jsr     wait_{pc:04x}           ; was {load} / {branch} *-{n}: {what}"]
        if n + 2 > 3:
            inc.append(f"        .res    {n + 2 - 3}, $EA")
        inc += ['        .segment "WAITS"']
        if first:
            inc += [f"wait_{pc:04x}:", "        jsr     mule_tick       ; (first: a longer loop comes back here)"]
            inc += [f"wait_{pc:04x}_check:"]
        else:
            inc += [f"wait_{pc:04x}:"]
        inc += [
                f"        {load.split()[0].lower()}     {load.split()[1]}",
                f"        {branch.lower()}     :+",
                "        rts",
                ":       jsr     mule_tick"]
        if target == pc:
            inc += [f"        jmp     wait_{pc:04x}{'_check' if first else ''}", ""]
        else:
            inc += ["        pla                     ; (not back here: to the loop's start)",
                    "        pla", f"        jmp     ${target:04X}", ""]
        areas.append({"start": f"{pc:04X}", "end": f"{pc + n + 1:04X}", "what": f"wait loop -> ticks: {what}"})
    for pc, (nbytes, what) in sorted(HEADS.items()):
        code, q = [], pc
        while q < pc + nbytes:
            mn, mode = dis6502.OPS[mem[q]]
            n = dis6502.MODES[mode]
            assert mn not in ("JMP", "JSR", "RTS", "RTI", "PHA", "PLA", "PHP", "PLP") and mode != "rel",                 f"${q:04X}: {mn} cannot move into a stub"
            code.append((mem[q:q + n], dis6502.fmt(mn, mode, mem[q + 1:q + n], q)))
            q += n
        assert q == pc + nbytes, f"${pc:04X}: {nbytes} bytes is not a whole number of instructions"
        inc += [f'        .segment "P_{pc:04X}"',
                f"        jsr     head_{pc:04x}           ; loop head: {what}"]
        if nbytes > 3:
            inc.append(f"        .res    {nbytes - 3}, $EA")
        inc += ['        .segment "WAITS"', f"head_{pc:04x}:", "        jsr     mule_tick"]
        inc += [f"        .byte   {', '.join(f'${b:02X}' for b in raw)}   ; {text}" for raw, text in code]
        inc += ["        rts", ""]
        areas.append({"start": f"{pc:04X}", "end": f"{pc + nbytes - 1:04X}", "what": f"wait loop head -> a tick: {what}"})
    for pc, what in sorted(CALLS.items()):
        assert mem[pc] == 0x20, f"${pc:04X}: not a JSR"
        target = mem[pc + 1] | mem[pc + 2] << 8
        inc += [f'        .segment "P_{pc:04X}"',
                f"        jsr     call_{pc:04x}           ; was JSR ${target:04X}, in a loop on {what}",
                '        .segment "WAITS"', f"call_{pc:04x}:", "        jsr     mule_tick",
                f"        jmp     ${target:04X}", ""]
        areas.append({"start": f"{pc:04X}", "end": f"{pc + 2:04X}", "what": f"wait loop call -> a tick first: {what}"})
    for pc, what in sorted(JUMPS.items()):
        assert mem[pc] == 0x4C, f"${pc:04X}: not a JMP"
        target = mem[pc + 1] | mem[pc + 2] << 8
        inc += [f'        .segment "P_{pc:04X}"',
                f"        jmp     jump_{pc:04x}           ; was JMP ${target:04X}, closing a loop on {what}",
                '        .segment "WAITS"', f"jump_{pc:04x}:", "        jsr     mule_tick",
                f"        jmp     ${target:04X}", ""]
        areas.append({"start": f"{pc:04X}", "end": f"{pc + 2:04X}", "what": f"wait loop jump -> a tick first: {what}"})
    with open(os.path.join(ROOT, "src", "waits.inc"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(inc))
    with open(os.path.join(ROOT, "src", "areas-waits.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(areas, f, indent=1)


if __name__ == "__main__":
    generate()
    print(f"{len(SITES)} + {len(HEADS)} + {len(CALLS)} + {len(JUMPS)} wait loops -> src/waits.inc, src/areas-waits.json")
