#!/usr/bin/env python3
"""
check-gaps.py - Report gaps between segments in ld65 debug output.

Parses the debug.txt file generated by ld65 and reports any gaps between
consecutive segments.

Usage:
    python3 check-gaps.py debug.txt

Exit code:
    0 - Always (report only, doesn't fail the build)
"""

import sys
import re


def parse_debug_file(filename):
    """Parse segment info from ld65 debug file."""
    segments = []

    # Pattern: seg id=N,name="NAME",start=0xADDR,size=0xSIZE,...
    seg_pattern = re.compile(
        r'seg\s+id=(\d+),name="([^"]+)",start=0x([0-9A-Fa-f]+),size=0x([0-9A-Fa-f]+)'
    )

    with open(filename, "r") as f:
        for line in f:
            match = seg_pattern.search(line)
            if match:
                seg_id = int(match.group(1))
                name = match.group(2)
                start = int(match.group(3), 16)
                size = int(match.group(4), 16)
                segments.append(
                    {
                        "id": seg_id,
                        "name": name,
                        "start": start,
                        "size": size,
                        "end": start + size,
                    }
                )

    return segments


def find_gaps(segments):
    """Find gaps between consecutive segments."""
    if not segments:
        return []

    # Filter out empty segments (size 0)
    segments = [s for s in segments if s["size"] > 0]

    # Sort by start address
    sorted_segs = sorted(segments, key=lambda s: s["start"])

    gaps = []
    for i in range(len(sorted_segs) - 1):
        curr = sorted_segs[i]
        next_seg = sorted_segs[i + 1]

        gap_start = curr["end"]
        gap_end = next_seg["start"]
        gap_size = gap_end - gap_start

        if gap_size > 0:
            gaps.append(
                {
                    "start": gap_start,
                    "end": gap_end,
                    "size": gap_size,
                    "after": curr["name"],
                    "before": next_seg["name"],
                }
            )
        elif gap_size < 0:
            # Overlap
            gaps.append(
                {
                    "start": gap_start,
                    "end": gap_end,
                    "size": gap_size,
                    "after": curr["name"],
                    "before": next_seg["name"],
                    "overlap": True,
                }
            )

    return gaps


def format_addr(addr):
    """Format address as 4-digit hex."""
    return f"${addr:04X}"


def main():
    if len(sys.argv) != 2:
        print(f"Usage: {sys.argv[0]} debug.txt", file=sys.stderr)
        sys.exit(1)

    debug_file = sys.argv[1]

    try:
        segments = parse_debug_file(debug_file)
    except FileNotFoundError:
        print(f"Error: File not found: {debug_file}", file=sys.stderr)
        sys.exit(1)

    if not segments:
        print("No segments found in debug file.")
        sys.exit(0)

    gaps = find_gaps(segments)

    # Print segment summary
    print(f"Segments: {len(segments)}")
    print()

    if not gaps:
        print("No gaps found - all segments are contiguous.")
        sys.exit(0)

    # Separate overlaps from gaps
    overlaps = [g for g in gaps if g.get("overlap")]
    real_gaps = [g for g in gaps if not g.get("overlap")]

    # Print gaps report
    if real_gaps:
        total_gap = sum(g["size"] for g in real_gaps)
        print(f"Gaps found: {len(real_gaps)} ({total_gap} bytes total)")
        print()
        print(f"{'Start':<8} {'End':<8} {'Size':>6}   Between")
        print("-" * 60)
        for gap in real_gaps:
            print(
                f"{format_addr(gap['start']):<8} {format_addr(gap['end']):<8} {gap['size']:>6}   "
                f"{gap['after']} -> {gap['before']}"
            )

    # Print overlaps (errors)
    if overlaps:
        print()
        print(f"OVERLAPS found: {len(overlaps)} (this is an error!)")
        print()
        for gap in overlaps:
            print(f"  {gap['after']} overlaps {gap['before']} by {-gap['size']} bytes")

    # Report only - don't fail the build
    sys.exit(0)


if __name__ == "__main__":
    main()
